def parse_q_line(s: str) -> list[str]:
    """argv as bash's printf %q wrote it, space separated."""
    words = []
    i = 0
    while i < len(s):
        if s[i] == " ":
            i += 1
            continue
        w, i = parse_word(s, i)
        words.append(unph(w.value))
    return words


def cmd_normalize(args):
    ctx = scrub_context(extra_home=args.home)
    by_file: dict[str, dict[str, set[str]]] = {name: defaultdict(set) for name in CONTAINER_FILES}
    for raw in Path(args.log).read_text(errors="replace").splitlines():
        if not raw.strip():
            continue
        origin, argv_q = raw.split("\t", 1)
        argv = split_semicolons(parse_q_line(argv_q))
        name = {"cli": "container-cli.argv", "pane": "container-pane.argv", "job": "container-job.argv"}[origin]
        by_file[name][to_line(normalize_argv(argv, ctx))].add(f"container:{origin}")
    for dump, label in ((args.list_keys, "list-keys"), (args.hooks, "show-hooks")):
        if not dump:
            continue
        for raw in Path(dump).read_text(errors="replace").splitlines():
            if label == "show-hooks":
                # show-hooks prints `name[idx] command`: store the set-hook
                # that recreates it, with tmux's own printing of the command
                parts = raw.split(None, 1)
                if len(parts) < 2:
                    continue  # a hook with no command
                cmds = [["set-hook", "-g", re.sub(r"\[\d+\]$", "", parts[0]), parts[1]]]
            else:
                cmds = scan_conf(raw)
            for cmd in cmds:
                by_file["container-stored.argv"][to_line(normalize_argv(cmd, ctx, conf=True))].add(f"container:{label}")
    write_corpus(by_file)
    print("normalize: " + ", ".join(f"{k} {len(v)}" for k, v in by_file.items()))


