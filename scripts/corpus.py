POSITION_LETTERS = {"M", "W", "S", "C", "P", "R"}


def form_of(p: Parsed) -> str:
    if p.name is None:
        return f"(alias) {p.verb}" if p.verb in USER_ALIASES else f"?{p.verb}"
    toks = set()
    for f, v in p.flags:
        kind = p.spec.args.get(f, "") if p.spec else ""
        if v == "=" and ("target" in kind or kind in TARGET_ARGS):
            toks.add(f"-{f}[=]")
        elif f in "xy" and p.name in ("display-menu", "display-popup") and v in POSITION_LETTERS:
            toks.add(f"-{f}[{v}]")
        elif p.spec and f not in p.spec.bools and f not in p.spec.args:
            toks.add(f"-{f}!")  # not in tmux 3.7b's usage (it may still be a hidden flag)
        else:
            toks.add(f"-{f}")
    return " ".join([p.name] + sorted(toks, key=lambda t: (t[1].lower(), t[1].isupper(), t)))


def forms_of_line(argv: list[str], conf: bool) -> list[tuple[str, int]]:
    """(form, depth) for every command a corpus line holds; depth > 0 means
    a stored command (a bind body, hook, if-shell branch...)."""
    out = []
    if argv and argv[0].startswith("%"):
        return [(argv[0], 0)]
    rest = argv
    if not conf:
        gflags, rest = split_global(argv)
        if gflags or not rest:
            out.append(
                (" ".join(["tmux"] + sorted({"-" + f for f, _ in gflags})) if gflags or rest else "tmux (bare)", 0)
            )
    for item in walk(rest):
        if item[0] == "cmd":
            out.append((form_of(item[1]), item[2]))
    return out


@dataclass
class Rule:
    verb: str
    need: list[str]
    row: str


def load_rules() -> list[Rule]:
    rules = []
    for line in ROWS_FILE.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        pattern, row = line.split("\t")
        toks = pattern.split()
        rules.append(Rule(toks[0], toks[1:], row.strip()))
    return rules


def match_row(form: str, rules: list[Rule]) -> str | None:
    toks = form.split()
    verb, flags = toks[0], set(toks[1:])
    for r in rules:
        if r.verb == verb and all(n in flags for n in r.need):
            return r.row
    return None


def spec_rows() -> tuple[dict[str, str], list[str], list[str]]:
    """(area rows by name, command-table lines, out-of-scope lines) of 4.5."""
    text = SPEC.read_text()
    sect = text.split("### 4.5", 1)[1].split("\n### ", 1)[0]
    areas, cmd_lines, oos = {}, [], []
    part = "cmd"
    for line in sect.splitlines():
        if line.startswith("| Area |"):
            part = "area"
        elif "**Out of scope for compatibility**" in line:
            part = "oos"
        if not line.startswith("| ") or line.startswith("|---"):
            continue
        if part == "cmd" and not line.startswith("| Command |"):
            cmd_lines.append(line)
        elif part == "area" and not line.startswith("| Area |"):
            areas[line.split("|")[1].strip()] = line
        elif part == "oos" and not line.startswith("| Item |"):
            oos.append(line)
    return areas, cmd_lines, oos


def row_text(row: str, verb: str) -> str | None:
    """The spec line a row id names, or None if it names none."""
    areas, cmd_lines, oos = spec_rows()
    kind, _, key = row.partition(":")
    if kind == "area":
        return areas.get(key)
    if kind == "cmd":
        names = {verb}
        if verb in CMDS and CMDS[verb].alias:
            names.add(CMDS[verb].alias)
        for line in cmd_lines:
            if line.rstrip().endswith(f"| {key} |") and any(f"`{n}" in line for n in names):
                return line
        return None
    if kind == "oos":
        for line in oos:
            if key in line:
                return line
    return None


def verb_named(verb: str, text: str) -> bool:
    names = {verb}
    if verb in CMDS and CMDS[verb].alias:
        names.add(CMDS[verb].alias)
    return any(re.search(rf"(?<![\w-]){re.escape(n)}(?![\w-])", text) for n in names)


def unnamed_flags(form: str, text: str) -> list[str]:
    """Flags of a form that its spec row does not mention (approximate: a
    flag counts as named if `-x` appears anywhere in the row, alone or in a
    cluster such as `-gqv`)."""
    out = []
    for tok in form.split()[1:]:
        if not tok.startswith("-"):
            continue
        f = tok[1]
        if not re.search(rf"(?<![\w-])-[A-Za-z]*{re.escape(f)}", text):
            out.append(tok)
    return out


