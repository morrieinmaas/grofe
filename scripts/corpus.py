def write_corpus(by_file: dict[str, dict[str, set[str]]]):
    CORPUS.mkdir(parents=True, exist_ok=True)
    sources = read_sources()
    for name, lines in by_file.items():
        (CORPUS / name).write_text("".join(f"{line}\n" for line in sorted(lines)))
        sources[name] = lines
    rows = ["# corpus file\tline\tsource (where the invocation came from)"]
    for name in sorted(sources):
        for line in sorted(sources[name]):
            for src in sorted(sources[name][line]):
                rows.append(f"{name}\t{line}\t{src}")
    SOURCES_FILE.write_text("\n".join(rows) + "\n")


