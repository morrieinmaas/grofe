@dataclass
class CmdSpec:
    name: str
    alias: str | None
    bools: set[str] = field(default_factory=set)
    args: dict[str, str] = field(default_factory=dict)  # flag -> placeholder
    positionals: list[str] = field(default_factory=list)


# tmux's default command-alias option (3.7b): these resolve like aliases.
DEFAULT_COMMAND_ALIASES = {
    "split-pane": ["split-window"],
    "splitp": ["split-window"],
    "server-info": ["show-messages", "-JT"],
    "info": ["show-messages", "-JT"],
    "choose-window": ["choose-tree", "-w"],
    "choose-session": ["choose-tree", "-s"],
}


def _usage_groups(usage: str) -> list[tuple[str, bool]]:
    """Top-level words and bracket groups of a usage string: (text, optional)."""
    out, i, n = [], 0, len(usage)
    while i < n:
        c = usage[i]
        if c.isspace():
            i += 1
        elif c == "[":
            depth, j = 0, i
            while j < n:
                if usage[j] == "[":
                    depth += 1
                elif usage[j] == "]":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            out.append((usage[i + 1 : j], True))
            i = j + 1
        else:
            j = i
            while j < n and not usage[j].isspace() and usage[j] != "[":
                j += 1
            out.append((usage[i:j], False))
            i = j
    return out


def load_commands(path: Path = COMMANDS_FILE) -> dict[str, CmdSpec]:
    cmds: dict[str, CmdSpec] = {}
    for line in path.read_text().splitlines():
        m = re.match(r"^(\S+)(?: \((\S+)\))?\s*(.*)$", line)
        if not m:
            continue
        spec = CmdSpec(m.group(1), m.group(2))
        for text, optional in _usage_groups(m.group(3)):
            if text.startswith("-"):
                if "|" in text:
                    spec.bools.update(t.strip()[1:] for t in text.split("|"))
                elif " " in text:
                    flag, name = text.split(" ", 1)
                    spec.args[flag[1:]] = name
                else:
                    spec.bools.update(text[1:])
            elif text == "...":
                continue
            else:
                spec.positionals.append(text.split(" ")[0])
        cmds[spec.name] = spec
    return cmds


CMDS = load_commands() if COMMANDS_FILE.exists() else {}


def canonical(verb: str) -> tuple[str | None, list[str]]:
    """tmux's lookup: exact name, alias, default command-alias, unique prefix."""
    if verb in CMDS:
        return verb, []
    for spec in CMDS.values():
        if spec.alias == verb:
            return spec.name, []
    if verb in DEFAULT_COMMAND_ALIASES:
        target = DEFAULT_COMMAND_ALIASES[verb]
        return target[0], target[1:]
    if verb and not verb.startswith("-") and PH_OPEN not in verb:
        hits = [n for n in CMDS if n.startswith(verb)]
        if len(hits) == 1:
            return hits[0], []
    return None, []


GLOBAL_BOOLS = set("2CDlNuVvh")
GLOBAL_ARGS = set("cfLST")


def split_global(argv: list[str]) -> tuple[list[tuple[str, str | None]], list[str]]:
    flags: list[tuple[str, str | None]] = []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--":
            i += 1
            break
        if not a.startswith("-") or a == "-" or len(a) < 2:
            break
        j = 1
        while j < len(a):
            c = a[j]
            if c in GLOBAL_ARGS:
                if j + 1 < len(a):
                    flags.append((c, a[j + 1 :]))
                else:
                    i += 1
                    flags.append((c, argv[i] if i < len(argv) else None))
                break
            flags.append((c, None))
            j += 1
        i += 1
    return flags, argv[i:]


@dataclass
class Parsed:
    verb: str  # as written
    name: str | None  # canonical, None if unknown
    flags: list[tuple[str, str | None]]
    positionals: list[str]
    implied: int = 0  # leading flags that came from a default command-alias

    @property
    def spec(self) -> CmdSpec | None:
        return CMDS.get(self.name) if self.name else None

    def has(self, flag: str) -> bool:
        return any(f == flag for f, _ in self.flags)

    def value(self, flag: str) -> str | None:
        for f, v in self.flags:
            if f == flag:
                return v
        return None


def parse_cmd(argv: list[str]) -> Parsed:
    name, extra = canonical(argv[0])
    if name is None:
        return Parsed(argv[0], None, [], argv[1:])
    spec = CMDS[name]
    args = extra + argv[1:]
    flags: list[tuple[str, str | None]] = []
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--":
            i += 1
            break
        if not a.startswith("-") or a == "-" or len(a) < 2:
            break
        j = 1
        while j < len(a):
            c = a[j]
            if c in spec.args:
                if j + 1 < len(a):
                    flags.append((c, a[j + 1 :]))
                else:
                    i += 1
                    flags.append((c, args[i] if i < len(args) else None))
                break
            flags.append((c, None))
            j += 1
        i += 1
    return Parsed(argv[0], name, flags, args[i:], sum(len(a) - 1 for a in extra))


def split_semicolons(argv: list[str]) -> list[str]:
    """tmux's CLI also ends a command at an argument ending in an unescaped
    `;` (`tmux start-server\\; show -g`): split it into the word and `;`."""
    out = []
    for a in argv:
        if len(a) > 1 and a.endswith(";") and not a.endswith("\\;"):
            out += [a[:-1], ";"]
        else:
            out.append(a)
    return out


def split_chain(argv: list[str]) -> list[list[str]]:
    out, cur = [], []
    for a in argv:
        if a == ";":
            if cur:
                out.append(cur)
            cur = []
        else:
            cur.append(a)
    if cur:
        out.append(cur)
    return out


# --------------------------------------------------------------------------
# A shell scanner: finds simple commands and the strings nested in them
# --------------------------------------------------------------------------


@dataclass
class Word:
    value: str
    nested: list[str]


WORD_END = set(" \t\n;&|()<>")


def _parse_dollar(text: str, i: int) -> tuple[str, list[str], int]:
    n = len(text)
    if text.startswith("$((", i):
        depth, j = 0, i + 1
        while j < n:
            if text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        return ph("$((...))"), [], min(j + 1, n)
    if text.startswith("$(", i):
        _, _, j = scan_shell(text, i + 2, until_paren=True)
        return ph("$(...)"), [text[i + 2 : j - 1]], j
    if text.startswith("${", i):
        depth, j = 0, i + 1
        while j < n:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        body = text[i + 2 : j]
        m = re.match(r"[#!]?(\w+)", body)
        name = m.group(1) if m else "?"
        nested = []
        if "$(" in body:
            nested.append(body)
        return ("~" if name == "HOME" else ph("$" + name)), nested, min(j + 1, n)
    m = re.match(r"\$([A-Za-z_]\w*|[0-9@*#?$!-])", text[i:])
    if m:
        name = m.group(1)
        return ("~" if name == "HOME" else ph("$" + name)), [], i + m.end()
    return "$", [], i + 1


def _parse_dq(text: str, i: int) -> tuple[str, list[str], int]:
    """Double-quoted body starting after the opening quote."""
    val, nested, n = [], [], len(text)
    while i < n and text[i] != '"':
        c = text[i]
        if c == "\\" and i + 1 < n:
            nxt = text[i + 1]
            if nxt == "\n":
                i += 2
                continue
            if nxt in '$`"\\':
                val.append(nxt)
                i += 2
                continue
            val.append(c)
            i += 1
            continue
        if c == "$":
            v, ns, i = _parse_dollar(text, i)
            val.append(v)
            nested.extend(ns)
            continue
        if c == "`":
            j = i + 1
            while j < n and text[j] != "`":
                j += 2 if text[j] == "\\" else 1
            nested.append(text[i + 1 : j])
            val.append(ph("$(...)"))
            i = j + 1
            continue
        val.append(c)
        i += 1
    return "".join(val), nested, i + 1


def _ansi_c(body: str) -> str:
    table = {"n": "\n", "t": "\t", "\\": "\\", "'": "'", '"': '"', "e": "\x1b", "E": "\x1b", "a": "\a", "r": "\r"}
    out, i = [], 0
    while i < len(body):
        if body[i] == "\\" and i + 1 < len(body):
            out.append(table.get(body[i + 1], body[i + 1]))
            i += 2
        else:
            out.append(body[i])
            i += 1
    return "".join(out)


def parse_word(text: str, i: int) -> tuple[Word, int]:
    val, nested, n = [], [], len(text)
    while i < n and text[i] not in WORD_END:
        c = text[i]
        if c == "\\" and i + 1 < n:
            if text[i + 1] != "\n":
                val.append(text[i + 1])
            i += 2
        elif c == "'":
            j = text.find("'", i + 1)
            j = n if j == -1 else j
            s = text[i + 1 : j]
            val.append(s)
            nested.append(s)
            i = j + 1
        elif c == "$" and text.startswith("$'", i):
            j = i + 2
            while j < n and text[j] != "'":
                j += 2 if text[j] == "\\" else 1
            val.append(_ansi_c(text[i + 2 : j]))
            i = j + 1
        elif c == '"':
            v, ns, i = _parse_dq(text, i + 1)
            val.append(v)
            nested.extend(ns)
            nested.append(v)
        elif c == "$":
            v, ns, i = _parse_dollar(text, i)
            val.append(v)
            nested.extend(ns)
        elif c == "`":
            j = i + 1
            while j < n and text[j] != "`":
                j += 2 if text[j] == "\\" else 1
            nested.append(text[i + 1 : j])
            val.append(ph("$(...)"))
            i = j + 1
        else:
            val.append(c)
            i += 1
    return Word("".join(val), nested), i


REDIRECT_RE = re.compile(r"\d*(>>|>&|>\||<<<|<<-?|<>|<&|>|<)|&>>?")


def scan_shell(text: str, i: int = 0, until_paren: bool = False):
    """Split shell text into simple commands (lists of Words).

    Returns (commands, nested strings, end index). With until_paren, stops
    after the `)` that closes a `$(`.
    """
    cmds: list[list[Word]] = []
    cur: list[Word] = []
    nested: list[str] = []
    heredocs: list[str] = []
    case_depth = 0
    n = len(text)

    def end_cmd():
        nonlocal cur
        if cur:
            cmds.append(cur)
        cur = []

    while i < n:
        c = text[i]
        if c in " \t":
            i += 1
            continue
        if c == "\\" and i + 1 < n and text[i + 1] == "\n":
            i += 2
            continue
        if c == "\n":
            end_cmd()
            i += 1
            for delim in heredocs:
                while i < n:
                    j = text.find("\n", i)
                    j = n if j == -1 else j
                    line = text[i:j]
                    i = j + 1
                    if line.strip() == delim:
                        break
            heredocs = []
            continue
        if c == "#" and text[i + 1 : i + 2] not in ("{", "(", "["):
            # `#{`, `#(` and `#[` are tmux format syntax in a string tmux
            # expands before the shell sees it, not a comment
            j = text.find("\n", i)
            i = n if j == -1 else j
            continue
        if c == ")":
            if until_paren and case_depth == 0:
                end_cmd()
                return cmds, nested, i + 1
            end_cmd()
            i += 1
            continue
        if c in "<>" and i + 1 < n and text[i + 1] == "(":
            # process substitution: a word whose body is shell
            _, _, j = scan_shell(text, i + 2, until_paren=True)
            nested.append(text[i + 2 : j - 1])
            cur.append(Word(ph("<(...)"), [text[i + 2 : j - 1]]))
            i = j
            continue
        m = REDIRECT_RE.match(text, i)
        if m and (c in "<>&" or (c.isdigit() and m.group(0)[-1] in "<>&|-")):
            op = m.group(0)
            i = m.end()
            while i < n and text[i] in " \t":
                i += 1
            if op.lstrip("0123456789").startswith("<<") and not op.endswith("<<<"):
                w, i = parse_word(text, i)
                heredocs.append(w.value)
                continue
            if i < n and text[i] not in WORD_END:
                w, i = parse_word(text, i)
                nested.extend(w.nested)
            continue
        if c in ";&|(":
            end_cmd()
            i += 2 if text[i : i + 2] in (";;", "&&", "||", "|&", ";&") else 1
            continue
        w, i = parse_word(text, i)
        if not cur and w.value == "case":
            case_depth += 1
        elif not cur and w.value == "esac":
            case_depth = max(0, case_depth - 1)
        cur.append(w)
        nested.extend(w.nested)
    end_cmd()
    return cmds, nested, i


# --------------------------------------------------------------------------
# A tmux config scanner (cmd-parse.y, approximately)
# --------------------------------------------------------------------------


def _conf_expand(text: str, i: int) -> tuple[str, int]:
    m = re.match(r"\$\{(\w+)\}|\$(\w+)", text[i:])
    if not m:
        return "$", i + 1
    name = m.group(1) or m.group(2)
    return ("~" if name == "HOME" else ph("$" + name)), i + m.end()


def _conf_word(text: str, i: int) -> tuple[str, int, bool]:
    """One config word. Returns (value, end, ends_command)."""
    val, n = [], len(text)
    while i < n and text[i] not in " \t\n":
        c = text[i]
        if c == "\\" and i + 1 < n:
            if text[i + 1] == "\n":
                i += 2  # a continuation inside a word joins the lines
                continue
            val.append(text[i + 1])
            i += 2
        elif c == "'":
            j = text.find("'", i + 1)
            j = n if j == -1 else j
            val.append(text[i + 1 : j])
            i = j + 1
        elif c == '"':
            i += 1
            while i < n and text[i] != '"':
                if text[i] == "\\" and i + 1 < n:
                    nxt = text[i + 1]
                    if nxt == "\n":
                        i += 2
                        continue
                    val.append(nxt if nxt in '"\\$' else "\\" + nxt)
                    i += 2
                elif text[i] == "$":
                    v, i = _conf_expand(text, i)
                    val.append(v)
                else:
                    val.append(text[i])
                    i += 1
            i += 1
        elif c == "$":
            v, i = _conf_expand(text, i)
            val.append(v)
        elif c == ";" and (i + 1 >= n or text[i + 1] in " \t\n"):
            return "".join(val), i + 1, True
        else:
            val.append(c)
            i += 1
    return "".join(val), i, False


def scan_conf(text: str) -> list[list[str]]:
    """Split tmux config text into commands. `\\;` stays as a lone `;` word
    inside a command (a separator its argument list carries, as for bind);
    a bare `;` ends the command."""
    cmds: list[list[str]] = []
    cur: list[str] = []
    i, n = 0, len(text)

    def end():
        nonlocal cur
        if cur:
            cmds.append(cur)
        cur = []

    while i < n:
        c = text[i]
        if c in " \t":
            i += 1
        elif c == "\\" and i + 1 < n and text[i + 1] == "\n":
            i += 2
        elif c == "\n":
            end()
            i += 1
        elif c == "#" and not text.startswith("#{", i):
            j = text.find("\n", i)
            i = n if j == -1 else j
        elif c == ";":
            end()
            i += 1
        elif c == "%" and not cur:
            j = text.find("\n", i)
            j = n if j == -1 else j
            line = text[i:j].split(None, 1)
            cmds.append([line[0]] + ([line[1].strip()] if len(line) > 1 else []))
            i = j
        elif c == "{" and (i + 1 >= n or text[i + 1] in " \t\n"):
            depth, j = 0, i
            while j < n:
                if text[j] == "{":
                    depth += 1
                elif text[j] == "}":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            cur.append(text[i + 1 : j].strip())
            i = j + 1
        else:
            w, i, ends = _conf_word(text, i)
            cur.append(w)
            if ends:
                end()
    end()
    return cmds


# --------------------------------------------------------------------------
# Walking a tmux command: nested commands, shell strings, formats
# --------------------------------------------------------------------------

SHELL_POSITIONAL = {"shell-command"}
TARGET_ARGS = {"src-pane", "dst-pane", "src-window", "dst-window"}


def _command_string(s: str) -> list[list[str]]:
    """A stored tmux command string (bind body, hook, if-shell branch)."""
    out = []
    for cmd in scan_conf(s):
        out.extend(split_chain(cmd))
    return out


def walk(argv: list[str], depth: int = 0):
    """Yield ('cmd', Parsed, depth), ('shell', str) and ('fmt', str) for a
    tmux argv (after global flags), recursing into stored command strings."""
    if depth > 6:
        return
    for sub in split_chain(argv):
        if not sub:
            continue
        p = parse_cmd(sub)
        if p.name is None and is_dynamic(p.verb):
            continue  # a command only known at run time (the recording has it)
        yield ("cmd", p, depth)
        if p.name is None:
            continue
        for f, v in p.flags:
            if v is not None and "#" in v:
                yield ("fmt", v)
        pos = p.positionals
        nested_cmds: list[list[str]] = []
        if p.name == "bind-key" and len(pos) > 1:
            body = pos[1:]
            if len(body) == 1 and (" " in body[0] or "\n" in body[0]):
                nested_cmds += _command_string(body[0])
            else:
                nested_cmds += split_chain(body)
        elif p.name == "if-shell" and pos:
            if p.has("F"):
                yield ("fmt", pos[0])
            else:
                yield ("shell", pos[0])
            for s in pos[1:3]:
                nested_cmds += _command_string(s)
        elif (
            p.name
            in ("confirm-before", "command-prompt", "choose-tree", "choose-client", "choose-buffer", "display-panes")
            and pos
        ):
            nested_cmds += _command_string(pos[0])
        elif p.name == "set-hook" and len(pos) > 1:
            nested_cmds += _command_string(pos[1])
        elif p.name == "display-menu":
            k = 0
            while k < len(pos):
                if pos[k] == "" or pos[k].startswith("-"):
                    k += 1
                    continue
                if k + 2 < len(pos):
                    nested_cmds += _command_string(pos[k + 2])
                k += 3
        elif p.name == "run-shell" and pos:
            if p.has("C"):
                nested_cmds += _command_string(" ".join(pos))
            else:
                yield ("shell", " ".join(pos))
        elif p.name in ("set-option", "set-window-option") and len(pos) > 1:
            if pos[0].startswith("command-alias") and "=" in pos[1]:
                nested_cmds += _command_string(pos[1].split("=", 1)[1])
            else:
                yield ("fmt", pos[1])
        elif p.name == "display-message" and pos:
            yield ("fmt", pos[0])
        elif p.spec and p.spec.positionals and p.spec.positionals[-1] in SHELL_POSITIONAL and pos:
            yield ("shell", " ".join(pos))
        if p.name == "detach-client" and p.value("E"):
            yield ("shell", p.value("E"))
        for c in nested_cmds:
            yield from walk(c, depth + 1)


def is_dynamic(verb: str) -> bool:
    return verb.startswith(("<", "#{", PH_OPEN)) or verb == ""


# Verbs the corpus itself defines through the command-alias option (which-key
# does this); learn_aliases fills it before forms are computed.
USER_ALIASES: set[str] = set()


def learn_aliases(corpus: dict[str, list[str]]):
    for lines in corpus.values():
        for line in lines:
            for m in re.finditer(r"command-alias\[\d*\]'? '?([A-Za-z][\w-]*)=", line):
                USER_ALIASES.add(m.group(1))


def unknown_flags(argv: list[str]) -> list[str]:
    """Flags tmux 3.7b does not have, in the top-level commands of an argv."""
    out = []
    for sub in split_chain(argv):
        p = parse_cmd(sub)
        if p.spec:
            out += [f for f, _ in p.flags if f not in p.spec.bools and f not in p.spec.args]
    return out


def hash_paren_bodies(s: str) -> list[str]:
    """The shell bodies of #(...) jobs in a format string."""
    out, i = [], 0
    while True:
        i = s.find("#(", i)
        if i == -1:
            return out
        depth, j = 0, i + 1
        while j < len(s):
            if s[j] == "(":
                depth += 1
            elif s[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        out.append(s[i + 2 : j])
        i = j


