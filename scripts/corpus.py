# Placeholders are built with control characters during extraction, so a
# placeholder can never be mistaken for shell syntax when a string is scanned
# again; they become <...> on output.
PH_OPEN, PH_CLOSE = "\x01", "\x02"


def ph(name: str) -> str:
    return f"{PH_OPEN}{name}{PH_CLOSE}"


def unph(s: str) -> str:
    return s.replace(PH_OPEN, "<").replace(PH_CLOSE, ">")


# --------------------------------------------------------------------------
# tmux's command table, from `tmux list-commands` (3.7b)
