def cmd_extract(args):
    col = Collector()
    for label, root, rel in static_sources(os.environ):
        if not (root / rel).exists():
            print(f"extract: missing source {label}:{rel}", file=sys.stderr)
            continue
        for path in iter_files(root, rel):
            kind = classify(path)
            if kind is None:
                continue
            source = f"{label}:{path.relative_to(root)}"
            text = path.read_text(errors="replace")
            if path.name.endswith(".tmpl") or ".chezmoitemplates" in path.parts:
                text = render_template(text)
            if kind == "systemd":
                text = re.sub(r"^Exec\w+=-?", "", text, flags=re.MULTILINE)
                kind = "shell"
            if kind == "shell":
                extract_shell(text, col, source)
            elif kind == "conf":
                extract_conf(text, col, source)
            elif kind == "keys":
                extract_keys_tsv(text, col, source)
            else:
                extract_code(text, col, source, kind)
    if MANUAL_FILE.exists():
        extract_manual(MANUAL_FILE.read_text(), col)
    by_file: dict[str, dict[str, set[str]]] = {
        "static-cli.argv": defaultdict(set),
        "static-conf.argv": defaultdict(set),
    }
    ctx = scrub_context(extra_home=None)
    legacy = Counter()
    for argv, kind, source in col.records:
        norm = normalize_argv(list(argv), ctx, conf=(kind == "conf"))
        rest = norm if kind == "conf" else split_global(norm)[1]
        if rest and canonical(rest[0])[0] in ("bind-key", "unbind-key") and "t" in unknown_flags(rest):
            # `bind -t vi-copy`: tmux-yank's branch for tmux before 2.4,
            # which the owner's 3.7b never takes
            legacy[(source, to_line(norm)[:80])] += 1
            continue
        by_file[f"static-{kind}.argv"][to_line(norm)].add(source)
    write_corpus(by_file)
    if args.verbose:
        for (source, text), n in sorted(col.rejected.items()):
            print(f"rejected {source}: {text}", file=sys.stderr)
        for (source, text), n in sorted(legacy.items()):
            print(f"legacy {source}: {text}", file=sys.stderr)
    total = sum(len(v) for v in by_file.values())
    print(
        f"extract: {total} distinct lines ({', '.join(f'{k} {len(v)}' for k, v in by_file.items())}); {len(col.rejected)} rejected candidates, {len(legacy)} legacy forms dropped"
    )


