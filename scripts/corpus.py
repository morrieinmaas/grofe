def classify(path: Path) -> str | None:
    name = path.name
    if name.endswith((".md", ".json")):
        return None
    if name == "keys.tsv":
        return "keys"
    if name.endswith((".service.tmpl", ".service")):
        return "systemd"
    if path.parent.name == "gh-dash" and name == "config.yml":
        return "shell"  # gh-dash keybinding commands are shell strings
    if name.endswith((".tsv", ".yml", ".yaml")):
        return None
    try:
        head = path.read_text(errors="replace")[:200]
    except OSError:
        return None
    if head.startswith("#!"):
        return "shell"
    stem = name.removesuffix(".tmpl")
    if stem.endswith(".conf") or name == "init.tmux":
        return "conf"
    if path.suffix in (".sh", ".bash", ".tmux", ".zsh") or stem.endswith(".sh"):
        return "shell"
    if path.suffix in CODE_EXT:
        return CODE_EXT[path.suffix]
    return None


def iter_files(root: Path, rel: str = ""):
    base = root / rel if rel else root
    if base.is_file():
        yield base
        return
    for p in sorted(base.rglob("*")):
        if p.is_file() and not any(part in SKIP_DIRS for part in p.relative_to(base).parts[:-1]):
            yield p


def render_template(text: str) -> str:
    """chezmoi templates in athome: the home dir becomes $HOME; other
    directives become a placeholder or go away."""
    text = re.sub(r"\{\{-?\s*\.chezmoi\.homeDir\s*-?\}\}", "$HOME", text)
    text = re.sub(r'\{\{-?\s*lookPath "tmux"[^}]*\}\}', "tmux", text)
    text = re.sub(r"^\s*\{\{[^\n]*\}\}\s*\n", "", text, flags=re.MULTILINE)
    return re.sub(r"\{\{[^\n]*?\}\}", ph("template"), text)


