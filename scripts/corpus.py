def normalize_command_string(s: str) -> str:
    """A stored tmux command string (if-shell branch, hook, confirm-before,
    one-string bind body) with its targets normalized like a top-level
    command. Left as written when normalizing changes nothing."""
    try:
        raw = _command_string(s)
    except (ValueError, IndexError):
        return s
    norm = [normalize_cmd(c) for c in raw]
    return _render(norm) if _render(norm) != _render(raw) else s


def normalize_cmd(sub: list[str]) -> list[str]:
    p = parse_cmd(sub)
    if p.name is None:
        return sub
    spec = p.spec
    out = [p.verb]
    for f, v in p.flags[p.implied :]:
        if v is None:
            out.append("-" + f)
            continue
        kind = spec.args.get(f, "") if spec else ""
        if "target" in kind or kind in TARGET_ARGS:
            v = norm_target(v, kind)
        elif kind in VALUE_NAMES and not is_opaque(v):
            v = VALUE_NAMES[kind]
        elif kind == "environment" and "=" in v:
            v = v.split("=", 1)[0] + "=<value>"
        out += ["-" + f, v]
    pos = list(p.positionals)
    if (
        p.name in ("set-option", "set-window-option")
        and len(pos) > 1
        and pos[0].startswith("@")
        or p.name == "set-environment"
        and len(pos) > 1
    ):
        pos[1:] = ["<value>"]
    elif p.name in ("rename-session", "rename-window") and pos and not is_opaque(pos[0]):
        pos[0] = "<name>"
    elif p.name in ("source-file", "load-buffer", "save-buffer") and pos:
        pos = [x if x == "/dev/null" or is_opaque(x) else "<file>" for x in pos]
    elif p.name == "if-shell" and len(pos) > 1:
        pos[1:3] = [normalize_command_string(x) for x in pos[1:3]]
    elif p.name == "confirm-before" and pos:
        pos[0] = normalize_command_string(pos[0])
    elif p.name == "set-hook" and len(pos) > 1:
        pos[1] = normalize_command_string(pos[1])
    elif p.name == "bind-key" and len(pos) > 1:
        body = pos[1:]
        if len(body) == 1 and " " in body[0]:
            pos = [pos[0], normalize_command_string(body[0])]
        else:
            norm_body: list[str] = []
            for c in split_chain(body):
                if norm_body:
                    norm_body.append(";")
                norm_body += normalize_cmd(c)
            pos = [pos[0]] + norm_body
    if pos and (len(pos[0]) > 1 and pos[0].startswith("-")) and p.name != "display-menu":
        out.append("--")
    return out + pos


def normalize_argv(argv: list[str], ctx: ScrubContext, conf: bool = False) -> list[str]:
    argv = [scrub(a, ctx) for a in argv]
    if conf and argv and argv[0].startswith("%"):
        return argv
    out: list[str] = []
    if not conf:
        gflags, rest = split_global(argv)
        for f, v in gflags:
            if v is None:
                out.append("-" + f)
            elif f == "L":
                out += ["-L", v if is_opaque(v) else "<socket>"]
            elif f == "S":
                out += ["-S", v if is_opaque(v) else "<socket-path>"]
            elif f == "f":
                out += ["-f", v if v == "/dev/null" or is_opaque(v) else "<file>"]
            else:
                out += ["-" + f, v]
    else:
        rest = argv
    first = True
    for sub in split_chain(rest):
        if not first:
            out.append(";")
        first = False
        out += normalize_cmd(sub)
    return out


SAFE_TOKEN = re.compile(r"[^\s'\"\\]+")


def quote(tok: str) -> str:
    if tok == ";":
        return "\\;"
    if SAFE_TOKEN.fullmatch(tok):
        return tok
    return shlex.quote(tok)


def to_line(argv: list[str]) -> str:
    # one invocation per line, and sources.tsv stays three columns: an
    # embedded newline or tab is written as the two characters \n or \t
    # (read back as those two characters; lossy only inside shell strings and
    # formats, whose forms do not depend on it)
    return " ".join(quote(a) for a in argv).replace("\n", "\\n").replace("\t", "\\t")


def from_line(line: str) -> list[str]:
    return [t.replace("\\n", "\n").replace("\\t", "\t") for t in shlex.split(line)]


