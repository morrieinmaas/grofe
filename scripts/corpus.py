def collect(corpus: dict[str, list[str]]):
    sources = read_sources()
    learn_aliases(corpus)
    forms: dict[str, dict] = {}
    options: Counter = Counter()
    user_opts: Counter = Counter()
    hooks: Counter = Counter()
    fmt_tokens: Counter = Counter()
    for fname, lines in corpus.items():
        conf = fname in ("static-conf.argv", "container-stored.argv")
        for line in lines:
            argv = from_line(line)
            srcs = sources.get(fname, {}).get(line, set())
            for form, depth in forms_of_line(argv, conf):
                e = forms.setdefault(form, {"lines": 0, "files": Counter(), "stored": 0, "sources": set()})
                e["lines"] += 1
                e["files"][fname] += 1
                e["stored"] += depth > 0
                e["sources"].update(srcs)
            rest = argv if conf else split_global(argv)[1]
            for item in walk(rest):
                if item[0] != "cmd" or item[1].name is None:
                    continue
                p = item[1]
                if (
                    p.name in ("set-option", "set-window-option", "show-options", "show-window-options")
                    and p.positionals
                ):
                    opt = re.sub(r"\[(\d*|<[^<>]*>)\]$", "[N]", p.positionals[0])
                    if opt.startswith("@"):
                        user_opts[re.sub(r"^(@[a-z]+[-_]?).*$", r"\1*", opt)] += 1
                    elif not opt.startswith("<"):
                        options[opt] += 1
                if p.name in ("set-hook", "show-hooks") and p.positionals and not p.positionals[0].startswith("<"):
                    hooks[re.sub(r"\[\d*\]$", "", p.positionals[0])] += 1
            for tok in argv:
                scan_format(tok, fmt_tokens)
    return forms, options, user_opts, hooks, fmt_tokens


MODIFIER_RE = re.compile(r"^([a-z]+(?:/[a-z]+)?|==|!=|>=?|<=?|&&|\|\|):")


def _split_top(s: str) -> list[str]:
    parts, depth, cur = [], 0, []
    for c in s:
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    parts.append("".join(cur))
    return parts


def scan_format(s: str, out: Counter, depth: int = 0):
    """Count the format vocabulary in s: #{var}, modifiers, conditions on
    bare names, short forms, styles, #() jobs, ## escapes."""
    if depth > 8:
        return
    for m in re.finditer(r"(?<!#)#([SIWhHPDTF])", s):
        out["short #" + m.group(1)] += 1
    for m in re.finditer(r"#\[(range|align|norange)", s):
        out["style #[" + m.group(1)] += 1
    if "#(" in s:
        out["job #(cmd)"] += s.count("#(")
    if "##" in s:
        out["escape ##"] += 1
    i = 0
    while True:
        i = s.find("#{", i)
        if i == -1:
            return
        d, j = 0, i + 1
        while j < len(s):
            if s[j] == "{":
                d += 1
            elif s[j] == "}":
                d -= 1
                if d == 0:
                    break
            j += 1
        body = s[i + 2 : j]
        i = j
        m = MODIFIER_RE.match(body)
        if body.startswith("?"):
            out["modifier ?"] += 1
            parts = _split_top(body[1:])
            cond = parts[0]
            if re.fullmatch(r"@?[a-z_]+|#[A-Za-z]", cond):
                out["conditions on bare names"] += 1
                if not cond.startswith(("@", "#")):
                    out["#{" + cond + "}"] += 1
            for part in parts:
                scan_format(part, out, depth + 1)
        elif m:
            out["modifier " + m.group(1) + ":"] += 1
            for part in _split_top(body[m.end() :]):
                if re.fullmatch(r"[a-z_]+", part) and m.group(1) in ("b", "t", "d"):
                    out["#{" + part + "}"] += 1
                scan_format(part, out, depth + 1)
        elif body.startswith("@"):
            out["#{@user_option}"] += 1
        elif re.fullmatch(r"[a-z_]+", body):
            out["#{" + body + "}"] += 1
        else:
            scan_format(body, out, depth + 1)


def generate_section() -> str:
    corpus = read_corpus()
    rules = load_rules()
    forms, options, user_opts, hooks, fmt_tokens = collect(corpus)
    spec = SPEC.read_text()
    sect = spec.split("### 4.5", 1)[1].split("\n### ", 1)[0]
    total_lines = sum(len(v) for v in corpus.values())
    out = [GEN_START, ""]
    out.append("### Corpus size")
    out.append("")
    out.append("| File | Lines |")
    out.append("|---|---|")
    for name in ARGV_FILES:
        out.append(f"| `tests/compat/corpus/{name}` | {len(corpus[name])} |")
    out.append(f"| total | {total_lines} |")
    out.append("")
    out.append(f"Distinct forms (verb plus flag set, stored commands included): **{len(forms)}**.")
    out.append("")
    out.append("### Forms")
    out.append("")
    out.append(
        "One row per distinct form. *Lines* counts corpus lines holding it; *stored* counts those where it sits inside a stored command (a bind body, hook, `if-shell` branch, menu item). *Verb named* says whether the mapped row mentions the verb at all, and *unnamed flags* lists flags it does not mention (both an approximate text match): a **no** or a listed flag is a question for the task that owns the row, not an error. A flag marked `!` is one tmux 3.7b's `list-commands` usage leaves out; it may still be a hidden flag tmux accepts (`select-pane -P` is)."
    )
    out.append("")
    out.append("| Form | Lines | Stored | Files | Spec 4.5 row | Verb named | Unnamed flags | Sources |")
    out.append("|---|---|---|---|---|---|---|---|")
    abbrev = {
        "static-cli.argv": "sc",
        "static-conf.argv": "sf",
        "container-cli.argv": "cc",
        "container-pane.argv": "cp",
        "container-job.argv": "cj",
        "container-stored.argv": "cs",
    }
    for form in sorted(forms, key=lambda f: (f.split()[0], f)):
        e = forms[form]
        row = match_row(form, rules)
        verb = form.split()[0]
        text = row_text(row, verb) if row else None
        in_scope = bool(text) and row.startswith(("area:", "cmd:"))
        unnamed = ", ".join(f"`{t}`" for t in unnamed_flags(form, text)) if in_scope else ""
        named = ("yes" if verb_named(verb, text) else "**no**") if in_scope and verb not in ("tmux", "(alias)") else ""
        files = " ".join(f"{abbrev[k]}{v}" for k, v in sorted(e["files"].items()))
        srcs = sorted(e["sources"])
        shown = ", ".join(s.replace("|", "\\|") for s in srcs[:3]) + (f" (+{len(srcs) - 3})" if len(srcs) > 3 else "")
        out.append(
            f"| `{form}` | {e['lines']} | {e['stored']} | {files} | {row or '**UNMAPPED**'} | {named} | {unnamed} | {shown} |"
        )
    out.append("")
    out.append(
        "File codes: `sc` static-cli, `sf` static-conf, `cc` container-cli, `cp` container-pane, `cj` container-job, `cs` container-stored."
    )
    out.append("")
    out.append("### Options by tmux name")
    out.append("")
    out.append(
        "Server, session, window and pane options the corpus sets or reads (`set`, `setw`, `show`, `showw`), with whether the spec names them anywhere (a text match: options live in section 5 as well as 4.5)."
    )
    out.append("")
    out.append("| Option | Uses | Named in the spec |")
    out.append("|---|---|---|")
    for opt, n in sorted(options.items()):
        base = opt.replace("[N]", "")
        out.append(f"| `{opt}` | {n} | {'yes' if base in spec else 'no'} |")
    out.append("")
    out.append(
        "User options, grouped by prefix: " + ", ".join(f"`{k}` ({v})" for k, v in sorted(user_opts.items())) + "."
    )
    out.append("")
    out.append("### Hooks")
    out.append("")
    out.append("| Hook | Uses | Named in 4.5 |")
    out.append("|---|---|---|")
    for h, n in sorted(hooks.items()):
        out.append(f"| `{h}` | {n} | {'yes' if h in sect else 'no'} |")
    out.append("")
    out.append("### Format vocabulary")
    out.append("")
    out.append(
        "Variables, modifiers, short forms and styles found in corpus tokens (a regex scan, so nested conditions are counted per occurrence). *Named in 4.5* is a text match over the section."
    )
    out.append("")
    out.append("| Token | Uses | Named in 4.5 |")
    out.append("|---|---|---|")
    for tok, n in sorted(fmt_tokens.items()):
        if tok.startswith("#{"):
            probe = tok[2:-1]
        elif tok.startswith("modifier "):
            probe = "#{" + tok.split(" ", 1)[1]
        else:
            probe = tok.split(" ", 1)[-1]
        named = probe in sect or probe.replace("|", "\\|") in sect
        shown = tok.replace("|", "\\|")
        out.append(f"| `{shown}` | {n} | {'yes' if named else 'no'} |")
    out.append("")
    out.append(GEN_END)
    return "\n".join(out)


