PREFIX_WORDS = {
    "if",
    "then",
    "else",
    "elif",
    "do",
    "while",
    "until",
    "!",
    "{",
    "}",
    "time",
    "exec",
    "command",
    "nohup",
    "builtin",
    "sudo",
}
TMUX_BIN_VARS = re.compile(PH_OPEN + r"\$(tmux|tmux_bin|canopy_tmux_bin|TMUX_BIN|TMUX_CMD|tmux_cmd)" + PH_CLOSE)
WRAPPERS = {"canopy_tmux_bare"}  # canopy/lib/tmux.sh: canopy_tmux_bare <tmux-bin> <argv...>


def tmux_argv_from(words: list[Word]) -> list[str] | None:
    vals = [w.value for w in words]
    k = 0
    while k < len(vals):
        v = vals[k]
        if v in PREFIX_WORDS or re.match(r"^[A-Za-z_]\w*=", v):
            k += 1
        elif v == "env":
            k += 1
            while k < len(vals) and (vals[k].startswith("-") or re.match(r"^[A-Za-z_]\w*=", vals[k])):
                k += 2 if vals[k] == "-u" else 1
        elif v == "xargs":
            k += 1
            while k < len(vals) and vals[k].startswith("-"):
                k += 2 if vals[k] in ("-I", "-n", "-d", "-L", "-P", "-s", "-E") else 1
        else:
            break
    if k >= len(vals):
        return None
    head = vals[k]
    if head == "tmux" or (head.endswith("/tmux") and "/" in head) or TMUX_BIN_VARS.fullmatch(head):
        return split_semicolons(vals[k + 1 :])
    if head in WRAPPERS and k + 1 < len(vals):
        return split_semicolons(vals[k + 2 :])
    return None


def valid_invocation(argv: list[str]) -> bool:
    _gflags, rest = split_global(argv)
    if not rest:
        return True
    return canonical(rest[0])[0] is not None


@dataclass
class Collector:
    records: list[tuple[tuple[str, ...], str, str]] = field(default_factory=list)
    rejected: Counter = field(default_factory=Counter)

    def emit(self, argv: list[str], kind: str, source: str):
        self.records.append((tuple(argv), kind, source))


def _scan_stored(argv: list[str], col: Collector, source: str, depth: int):
    """Follow a tmux argv into the shell strings and formats it carries."""
    for item in walk(argv):
        if item[0] == "shell":
            extract_shell(item[1], col, source, depth + 1)
        elif item[0] == "fmt":
            for body in hash_paren_bodies(item[1]):
                extract_shell(body, col, source, depth + 1)


def extract_shell(text: str, col: Collector, source: str, depth: int = 0):
    if depth > 6 or not text:
        return
    for body in hash_paren_bodies(text):
        extract_shell(body, col, source, depth + 1)
    cmds, nested, _ = scan_shell(text)
    for words in cmds:
        argv = tmux_argv_from(words)
        if argv is None:
            continue
        if valid_invocation(argv):
            col.emit(argv, "cli", source)
            _, rest = split_global(argv)
            _scan_stored(rest, col, source, depth)
        else:
            col.rejected[(source, unph(" ".join(argv))[:80])] += 1
    for s in nested:
        if "tmux" in s or TMUX_BIN_VARS.search(s) or any(w in s for w in WRAPPERS):
            extract_shell(s, col, source, depth + 1)


def extract_conf(text: str, col: Collector, source: str):
    for cmd in scan_conf(text):
        if cmd[0].startswith("%"):
            col.emit(cmd, "conf", source)
            continue
        if canonical(cmd[0])[0] is None:
            col.rejected[(source, unph(" ".join(cmd))[:80])] += 1
            continue
        col.emit(cmd, "conf", source)
        _scan_stored(cmd, col, source, 0)


def extract_keys_tsv(text: str, col: Collector, source: str):
    """canopy's key table: canopy-keys renders each row as `bind [flags] key
    cmd`, with ` ; ` in the command turned into a separator."""
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) != 6:
            continue
        body: list[str] = []
        for cmd in _command_string(f[3]):
            if body:
                body.append(";")
            body.extend(cmd)
        argv = ["bind"] + ([] if f[2] == "-" else f[2].split()) + [f[1]] + body
        col.emit(argv, "conf", source)
        _scan_stored(argv, col, source, 0)


STRING_LIT = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'')


def _unescape_literal(s: str) -> str:
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def extract_code(text: str, col: Collector, source: str, lang: str):
    """String literals in Rust, Lua, Vim script, Python or TypeScript: each is
    scanned as shell, and a list literal whose first string is a tmux verb is
    taken as an argv (non-literal elements become placeholders)."""
    if lang == "rs":
        text = text.split("#[cfg(test)]", 1)[0]
    lits = []
    for m in STRING_LIT.finditer(text):
        s = m.group(1) if m.group(1) is not None else m.group(2)
        s = _unescape_literal(s)
        if lang in ("rs", "py"):
            s = s.replace("{{", "\x03").replace("}}", "\x04")
            s = re.sub(r"\{[^{}]*\}", ph("fmt-arg"), s)
            s = s.replace("\x03", "{").replace("\x04", "}")
        lits.append(s)
        if "tmux" in s:
            extract_shell(s, col, source, 1)
    # list literals: [ "verb", ... ] or { "tmux", "verb", ... }
    for m in re.finditer(
        r"[\[{(]\s*((?:\"[^\"\n]*\"|'[^'\n]*'|[A-Za-z_][\w:.]*\([^()\n]*\)|[^\]\[{}()\n;]){1,400}?)[\]})]", text
    ):
        items = [x.strip() for x in re.split(r",(?![^()]*\))", m.group(1))]
        items = [x for x in items if x]
        if len(items) < 2:
            continue
        vals = []
        for x in items:
            lm = re.fullmatch(r'"([^"]*)"|\'([^\']*)\'', x)
            if lm:
                vals.append(lm.group(1) if lm.group(1) is not None else lm.group(2))
            else:
                vals.append(ph("expr"))
        if vals[0] == "tmux":
            vals = vals[1:]
        elif not re.fullmatch(r'"[a-z-]+"', items[0]):
            continue
        exact_names = set(CMDS) | {s.alias for s in CMDS.values() if s.alias}
        if not vals or vals[0] not in exact_names:
            continue
        col.emit(vals, "cli", source)


def extract_manual(text: str, col: Collector):
    """scripts/corpus-manual.txt: hand transcriptions of argv that code
    builds dynamically. `# source: <label>` sets the source for the lines
    after it."""
    source = "manual"
    for line in text.splitlines():
        if line.startswith("# source:"):
            source = "manual:" + line.split(":", 1)[1].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        argv = shlex.split(line)
        col.emit(argv, "cli", source)


