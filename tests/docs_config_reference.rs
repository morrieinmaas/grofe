//! `docs/config-reference.md` lists every option from the real options
//! tables, so it cannot go stale. Run with `GROFE_BLESS_DOCS=1` to rewrite
//! the generated part after changing an option.

use grofe::config::{Env, LIST_NAMES, OPTION_NAMES, Resolved, load, toml_type_name};
use std::fs;
use std::path::Path;

const START: &str = "<!-- generated by tests/docs_config_reference.rs: start -->";
const END: &str = "<!-- generated by tests/docs_config_reference.rs: end -->";

fn default_of(resolved: &Resolved, key: &str, ty: &str) -> String {
    let Some(v) = resolved.get(key) else {
        return "unset".to_string();
    };
    match (ty, v) {
        ("boolean", "on") => "`true`".to_string(),
        ("boolean", "off") => "`false`".to_string(),
        ("integer", "on") => "`1`".to_string(),
        ("integer", "off") => "`0`".to_string(),
        ("integer", n) => format!("`{n}`"),
        (_, s) => format!("`\"{}\"`", s.replace('|', "\\|")),
    }
}

fn generated() -> String {
    let resolved = load(&Env::from_vars(None, None)).expect("defaults load");
    let mut out = String::new();
    out.push_str("### Options\n\n");
    out.push_str("| TOML key | Type | Default | tmux option |\n|---|---|---|---|\n");
    let mut options: Vec<_> = OPTION_NAMES.to_vec();
    options.sort();
    for (key, tmux) in options {
        let ty = toml_type_name(key);
        out.push_str(&format!(
            "| `{key}` | {ty} | {} | `{tmux}` |\n",
            default_of(&resolved, key, ty)
        ));
    }
    out.push_str("\n### List options\n\n");
    out.push_str("An array of strings sets the whole list, element N from index N.\n\n");
    out.push_str("| TOML key | Type | Default elements | tmux option |\n|---|---|---|---|\n");
    let mut lists: Vec<_> = LIST_NAMES.to_vec();
    lists.sort();
    for (key, tmux) in lists {
        let n = resolved.lists.get(key).map_or(0, |l| l.len());
        out.push_str(&format!(
            "| `{key}` | array of strings | {n} | `{tmux}` |\n"
        ));
    }
    out
}

#[test]
fn config_reference_matches_the_options_tables() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/config-reference.md");
    let doc = fs::read_to_string(&path).expect("docs/config-reference.md exists");
    let (head, rest) = doc.split_once(START).expect("start marker");
    let (old, tail) = rest.split_once(END).expect("end marker");
    let want = format!("\n\n{}\n", generated());
    if std::env::var_os("GROFE_BLESS_DOCS").is_some() {
        fs::write(&path, format!("{head}{START}{want}{END}{tail}")).unwrap();
        return;
    }
    assert!(
        old == want,
        "docs/config-reference.md is stale; run GROFE_BLESS_DOCS=1 cargo test --test docs_config_reference"
    );
}

#[test]
fn every_option_is_documented_once() {
    let mut keys: Vec<&str> = OPTION_NAMES
        .iter()
        .chain(LIST_NAMES)
        .map(|(k, _)| *k)
        .collect();
    let total = keys.len();
    keys.sort();
    keys.dedup();
    assert_eq!(
        keys.len(),
        total,
        "a TOML key appears twice in the options tables"
    );
}
